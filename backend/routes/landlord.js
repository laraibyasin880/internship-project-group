const express = require('express')
const PDFDocument = require('pdfkit')
const router = express.Router()
const Landlord = require('../models/Landlord')
const Certificate = require('../models/Certificate')

function formatDate(value) {
  return new Date(value).toLocaleDateString('en-GB', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
  })
}

function getStatus(expires) {
  const days = Math.ceil((new Date(expires) - new Date()) / 86400000)
  if (days < 0) return 'Expired'
  if (days <= 30) return 'Expiring soon'
  return 'Valid'
}

router.get('/:token/certificates', async (req, res) => {
  try {
    const landlord = await Landlord.findOne({ token: req.params.token })

    if (!landlord) {
      return res.status(404).json({ message: 'Link is invalid or has expired' })
    }

    const certs = await Certificate.find({ landlordToken: landlord.token }).sort({ expires: -1 })

    res.json({
      name: landlord.name,
      property: landlord.property,
      certificates: certs.map((c) => ({
        id: c.certId,
        type: c.type,
        issued: c.issued,
        expires: c.expires,
        engineer: c.engineer,
      })),
    })
  } catch (err) {
    res.status(500).json({ message: 'Server error' })
  }
})

router.get('/:token/certificates/:certId/download', async (req, res) => {
  try {
    const landlord = await Landlord.findOne({ token: req.params.token })
    if (!landlord) {
      return res.status(404).json({ message: 'Link is invalid or has expired' })
    }

    const cert = await Certificate.findOne({
      certId: req.params.certId,
      landlordToken: landlord.token,
    })
    if (!cert) {
      return res.status(404).json({ message: 'Certificate not found' })
    }

    const doc = new PDFDocument({ size: 'A4', margin: 50 })
    res.setHeader('Content-Type', 'application/pdf')
    res.setHeader('Content-Disposition', `attachment; filename="${cert.certId}.pdf"`)
    doc.pipe(res)

    doc.rect(0, 0, doc.page.width, 90).fill('#1F3A5F')
    doc.fillColor('#FFFFFF').fontSize(24).text('TradesDash', 50, 32)

    doc.fillColor('#1B2430').fontSize(20).text(cert.type, 50, 130)
    doc.moveTo(50, 165).lineTo(545, 165).lineWidth(2).strokeColor('#E07B20').stroke()

    const rows = [
      ['Certificate ID', cert.certId],
      ['Landlord', landlord.name],
      ['Property', landlord.property || '-'],
      ['Issued on', formatDate(cert.issued)],
      ['Expires on', formatDate(cert.expires)],
      ['Status', getStatus(cert.expires)],
      ['Issued by', cert.engineer || '-'],
    ]

    let y = 195
    rows.forEach(([label, value]) => {
      doc.fontSize(10).fillColor('#5B6776').text(label, 50, y)
      doc.fontSize(13).fillColor('#1B2430').text(value, 200, y - 2)
      y += 36
    })

    doc.fontSize(9).fillColor('#5B6776').text('Generated by TradesDash', 50, 740)

    doc.end()
  } catch (err) {
    if (!res.headersSent) {
      res.status(500).json({ message: 'Server error' })
    }
  }
})

module.exports = router